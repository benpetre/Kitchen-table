// ---------------------------------------------------------------- countries
const topo = require('world-atlas/countries-50m.json');
const meta = require('world-countries');
const byNum = new Map(meta.filter((c) => c.ccn3).map((c) => [c.ccn3, c]));
const SIZE = 1000;
const MIN_AREA_KM2 = 500; // smaller than this has no readable outline at this scale
const NAME = { US: 'United States', GB: 'United Kingdom', CD: 'DR Congo', CG: 'Republic of the Congo', CZ: 'Czechia' };

function simplify(pts, tol) {
  // Douglas-Peucker on a closed ring (first point repeated at the end).
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let worst = 0, at = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy);
    for (let i = a + 1; i < b; i++) {
      // A closed ring starts with coincident ends: fall back to plain distance.
      const d = len ? Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len : Math.hypot(pts[i][0] - ax, pts[i][1] - ay);
      if (d > worst) { worst = d; at = i; }
    }
    if (worst > tol) { keep[at] = 1; stack.push([a, at], [at, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const countries = [];
for (const f of feature(topo, topo.objects.countries).features) {
  const m = byNum.get(String(f.id).padStart(3, '0'));
  if (!m || !(m.unMember || m.cca2 === 'TW' || m.cca2 === 'PS') || m.area < MIN_AREA_KM2) continue;

  // Keep the mainland and whatever sits near it; drop far-flung territories
  // (French Guiana, Alaska, Hawaii...) that would shrink the outline to a dot.
  const polys = (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).map((coordinates) => {
    const g = { type: 'Polygon', coordinates };
    return { g, area: geoArea(g), c: geoCentroid(g) };
  });
  polys.sort((a, b) => b.area - a.area);
  const main = polys[0];
  const total = polys.reduce((s, p) => s + p.area, 0);
  const kept = polys.filter((p) => p === main || (geoDistance(p.c, main.c) < 0.42 && p.area > total * 0.0015) || p.area > main.area * 0.5);
  const geom = { type: 'MultiPolygon', coordinates: kept.map((p) => p.g.coordinates) };
  const [lon, lat] = geoCentroid(geom);

  const proj = geoAzimuthalEqualArea().rotate([-lon, -lat]).fitExtent([[20, 20], [SIZE - 20, SIZE - 20]], geom);
  const path = geoPath(proj);
  let d = '';
  for (const p of kept) {
    const ring = p.g.coordinates[0].map((pt) => proj(pt));
    const s = simplify(ring, 1.6);
    if (s.length < 4) continue;
    d += 'M' + s.slice(0, -1).map(([x, y]) => `${Math.round(x)},${Math.round(y)}`).join('L') + 'Z';
  }
  if (!d || !(path.area(geom) > 0)) continue;
  countries.push({
    code: m.cca2,
    name: NAME[m.cca2] ?? m.name.common,
    lat: +lat.toFixed(2),
    lon: +lon.toFixed(2),
    region: m.subregion || m.region,
    path: d,
  });
}
// Natural Earth lists a few territories under their parent's ISO number: keep the mainland.
for (const c of [...countries]) {
  const twin = countries.find((o) => o !== c && o.code === c.code);
  if (twin && twin.path.length >= c.path.length) countries.splice(countries.indexOf(c), 1);
}
countries.sort((a, b) => a.name.localeCompare(b.name));
write(out('src/data/countries.json'), JSON.stringify(countries));
write(
  resolve(here, '../supabase/functions/games-api/data/countries.ts'),
  `// Generated by games/scripts/build-data.mjs - do not edit by hand.\n` +
    `/** Countries the app has an outline for: [code, name, region]. */\n` +
    `export const COUNTRIES: [string, string, string][] = ${JSON.stringify(countries.map((c) => [c.code, c.name, c.region]))};\n`,
);
console.log(`${valid5.length} guess words, ${common.length} common words, ${answers5.length} easy fives, ${countries.length} countries`);
