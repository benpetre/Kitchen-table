// Builds the static data the games ship with. Run from games/:  node scripts/build-data.mjs
//
//   src/data/words5.json        5-letter words accepted as guesses in Hunch
//   src/data/countries.json     country outlines + centroids for Outline
//   supabase/functions/games-api/data/words.ts      common 3-5 letter words (crossword fill, answer checks)
//   supabase/functions/games-api/data/countries.ts  code + name list the generator may pick from
//
// Sources: SCOWL word lists (wordlist-english), Natural Earth 1:50m (world-atlas),
